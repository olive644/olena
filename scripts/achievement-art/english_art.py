"""Export English badges without enlarging source pixels.

python scripts/achievement-art/english_art.py --plan docs/achievement-english-art-sources.json
Requires Pillow. Generated source PNGs remain in the workspace; source hashes,
native crop rectangles and output hashes are recorded in the plan for review.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

SIZE = 512
THUMBNAIL = 128
ROOT = Path(__file__).resolve().parents[2]


def native_cell(image, columns, rows, column, row):
    width, height = image.size
    rectangle = (
        round(column * width / columns), round(row * height / rows),
        round((column + 1) * width / columns), round((row + 1) * height / rows),
    )
    cell = image.crop(rectangle)
    if min(cell.size) < SIZE:
        raise ValueError(f"Native cell {cell.size} is smaller than {SIZE}px; upscaling is forbidden")
    if cell.width != cell.height:
        raise ValueError(f"Badge source must be square: {cell.size}")
    if "A" not in cell.getbands() or cell.getchannel("A").getextrema()[0] != 0:
        raise ValueError("Source must have transparent alpha outside the silhouette")
    return cell, rectangle


def number_position(cell):
    """Find the blank ivory plaque, keeping the shared 21-unit digit size."""
    image = cell.convert("RGBA")
    width, height = image.size
    left, right = round(width * .35), round(width * .65)
    runs = []
    start = None
    for y in range(round(height * .68), round(height * .92)):
        count = 0
        for x in range(left, right):
            red, green, blue, alpha = image.getpixel((x, y))
            count += (alpha > 240 and red > 220 and green > 180 and blue > 125
                      and red >= green >= blue and red - blue < 105)
        ivory = count / (right - left) > .95
        if ivory and start is None:
            start = y
        if not ivory and start is not None:
            runs.append((start, y))
            start = None
    if start is not None:
        runs.append((start, round(height * .92)))
    candidates = [run for run in runs if run[1] - run[0] >= height * .045]
    if not candidates:
        raise ValueError("Blank ivory number plaque not found; review the source")
    top, bottom = candidates[-1]
    return round(((top + bottom) / 2) / height * 160 - 10.5, 2)


def write_plates(plan_path, destination):
    plan = json.loads(plan_path.read_text())
    positions = {item["id"]: item["numberY"] for group in plan["groups"]
                 for item in group["cells"] if item["id"]}
    destination.write_text(
        '// Generated by scripts/achievement-art/english_art.py from the native ivory plaques.\n'
        'export const ENGLISH_ACHIEVEMENT_PLATES: Readonly<Record<string, number>> = '
        + json.dumps(positions, ensure_ascii=False, indent=2) + ';\n'
    )


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export_plan(plan_path, output, selected=None):
    plan = json.loads(plan_path.read_text())
    columns, rows = plan["grid"]
    staged = []
    groups = [group for group in plan["groups"] if not selected or group["id"] in selected]
    if not groups:
        raise ValueError("No selected source groups")
    # Validate all selected inputs before replacing any asset.
    for group in groups:
        path = Path(group["source"])
        with Image.open(path) as image:
            image.load()
            group["sourceSize"] = list(image.size)
            group["sourceSha256"] = digest(path)
            for index, item in enumerate(group["cells"]):
                if not item["id"]:
                    continue
                cell, rectangle = native_cell(image, columns, rows, index % columns, index // columns)
                item["numberY"] = number_position(cell)
                item["sourceRect"] = list(rectangle)
                item["nativeSize"] = list(cell.size)
                staged.append((item, cell.convert("RGBA")))
    output.mkdir(parents=True, exist_ok=True)
    (output / "thumb").mkdir(exist_ok=True)
    for item, cell in staged:
        full = output / f'{item["id"]}.webp'
        thumb = output / "thumb" / f'{item["id"]}.webp'
        cell.resize((SIZE, SIZE), Image.Resampling.LANCZOS).save(full, quality=90)
        cell.resize((THUMBNAIL, THUMBNAIL), Image.Resampling.LANCZOS).save(thumb, quality=85)
        item["outputSha256"] = digest(full)
        item["thumbnailSha256"] = digest(thumb)
    plan_path.write_text(json.dumps(plan, ensure_ascii=False, indent=2) + "\n")
    return len(staged)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "public/achievement-badges/english")
    parser.add_argument("--only", nargs="*")
    parser.add_argument("--plates", type=Path, default=ROOT / "src/data/english-achievement-plates.ts")
    args = parser.parse_args()
    count = export_plan(args.plan, args.output, set(args.only or []))
    if not args.only:
        write_plates(args.plan, args.plates)
    print(f"Exported {count} native-resolution badges and thumbnails; no upscaling")


if __name__ == "__main__":
    main()
