// Mesma proporção do número aprovado nas badges de Matemática: 14 por 21, a 1,6 abaixo do
// centro medido da placa e 0,2 à direita dele.
export function englishBadgeDigits(art: string, count: number) {
  const [cx, cy, width] = ENGLISH_BADGE_TABLET[art] ?? [79.8, 123.9, 67.2];
  const scale = Math.min(1, (0.92 * width) / (count * 14));
  return { x: cx + 0.2 - (count * 14 * scale) / 2, y: cy + 1.6 - (21 * scale) / 2, scale };
}
